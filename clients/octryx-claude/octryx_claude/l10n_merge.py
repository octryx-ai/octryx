"""``octryx-claude l10n-merge``: merge per-feature translation files into one file per language."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

MARKER_KEY = "@@x-generated"
PO_HEADER = "# Generated by octryx-claude l10n-merge from {source}; edit the feature files, never this one.\n"


def _files(root: Path, pattern: str) -> dict[str, list[Path]]:
    regex = re.compile("^" + re.escape(pattern).replace(re.escape("<lang>"), r"(?P<lang>[A-Za-z_-]+)")
                       .replace(r"\*", "[^/]+") + "$")
    out: dict[str, list[Path]] = {}
    for path in sorted(root.glob(pattern.replace("<lang>", "*"))):
        match = regex.match(path.relative_to(root).as_posix())
        if match and path.is_file():
            out.setdefault(match.group("lang"), []).append(path)
    return out


def merge_arb(paths: list[Path], locale: str, source: str) -> tuple[dict[str, Any], list[str]]:
    merged: dict[str, Any] = {"@@locale": locale, MARKER_KEY: f"by octryx-claude l10n-merge from {source}"}
    owners: dict[str, str] = {}
    duplicates = []
    for path in paths:
        for key, value in json.loads(path.read_text(encoding="utf-8")).items():
            if key.startswith("@@"):
                continue
            name = key.removeprefix("@")
            if not key.startswith("@") and name in owners:
                duplicates.append(f"{name} ({owners[name]} and {path})")
            owners.setdefault(name, str(path))
            merged[key] = value
    return merged, duplicates


def merge_po(paths: list[Path], source: str) -> tuple[str, list[str]]:
    seen: dict[str, str] = {}
    duplicates, blocks = [], []
    header = ""
    for path in paths:
        for block in path.read_text(encoding="utf-8").split("\n\n"):
            match = re.search(r'^msgid "(.*)"', block, re.MULTILINE)
            if match is None:
                continue
            if match.group(1) == "":
                header = header or block  # the first file's header entry
                continue
            if match.group(1) in seen:
                duplicates.append(f"{match.group(1)} ({seen[match.group(1)]} and {path})")
                continue
            seen[match.group(1)] = str(path)
            blocks.append(block.strip("\n"))
    return PO_HEADER.format(source=source) + "\n\n".join([header.strip("\n"), *blocks] if header else blocks) + "\n", \
        duplicates


def merge(root: Path, fmt: str, features: str, target: str) -> list[str]:
    problems: list[str] = []
    for locale, paths in sorted(_files(root, features).items()):
        out = root / target.replace("<lang>", locale)
        out.parent.mkdir(parents=True, exist_ok=True)
        if fmt == "arb":
            merged, duplicates = merge_arb(paths, locale, features)
            out.write_text(json.dumps(merged, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        else:
            text, duplicates = merge_po(paths, features)
            out.write_text(text, encoding="utf-8")
        problems += [f"{locale}: {item}" for item in duplicates]
    return problems


def main(args: list[str]) -> int:
    if len(args) != 3 or args[0] not in ("arb", "gettext"):
        print("usage: octryx-claude l10n-merge <arb|gettext> <feature pattern> <target pattern>", file=sys.stderr)
        return 2
    problems = merge(Path.cwd(), args[0], args[1], args[2])
    for problem in problems:
        print(f"duplicate key: {problem}", file=sys.stderr)
    return 1 if problems else 0


__all__ = ["MARKER_KEY", "main", "merge"]
