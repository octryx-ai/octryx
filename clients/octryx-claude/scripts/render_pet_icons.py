"""Render the Octryx mascot for the pet into ``octryx_claude/pet/icon_data.py`` (a dev tool, not shipped).

The served wheel carries only ``*.py`` (``backend/app/services/octryx_client/artifact.py``), so the mascot goes in as
base64 PNG. The source is the Octryx logo (``frontend/chat/public/octryx-logo.svg``). An SVG that embeds a
PNG is read and scaled here with Pillow; a pure vector SVG is rendered with ``rsvg-convert``.

    python scripts/render_pet_icons.py ../../frontend/chat/public/octryx-logo.svg
"""

from __future__ import annotations

import base64
import io
import re
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

SIZE = 128
OUT = Path(__file__).resolve().parents[1] / "octryx_claude" / "pet" / "icon_data.py"
_EMBEDDED = re.compile(r'<image\b([^>]*)\b(?:xlink:)?href="data:image/png;base64,([A-Za-z0-9+/=\s]+)"', re.S)
_ATTR = re.compile(r'\b(x|y|width|height)="(-?[0-9.]+)"')
_VIEWBOX = re.compile(r'viewBox="([0-9.\s-]+)"')


def _from_embedded(svg: str) -> Image.Image | None:
    match = _EMBEDDED.search(svg)
    if match is None:
        return None
    image = Image.open(io.BytesIO(base64.b64decode(re.sub(r"\s", "", match.group(2))))).convert("RGBA")
    attrs = {key: float(value) for key, value in _ATTR.findall(match.group(1))}
    box = [float(part) for part in _VIEWBOX.search(svg).group(1).split()] if _VIEWBOX.search(svg) else None
    if box and attrs.get("width") and attrs.get("height"):  # the part of the image the viewBox shows
        scale_x, scale_y = image.width / attrs["width"], image.height / attrs["height"]
        left, top = (box[0] - attrs.get("x", 0.0)) * scale_x, (box[1] - attrs.get("y", 0.0)) * scale_y
        image = image.crop((round(left), round(top), round(left + box[2] * scale_x), round(top + box[3] * scale_y)))
    return image


def _from_vector(path: Path) -> Image.Image:
    tool = shutil.which("rsvg-convert")
    if tool is None:
        raise SystemExit("rsvg-convert is needed for a vector SVG (brew install librsvg)")
    png = subprocess.run([tool, "-w", "1024", "-a", str(path)], capture_output=True, check=True).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA")


def mascot(path: Path) -> Image.Image:
    image = _from_embedded(path.read_text(encoding="utf-8")) or _from_vector(path)
    image = image.crop(image.getbbox())
    side = max(image.size)
    square = Image.new("RGBA", (side, side))
    square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))
    return square.resize((SIZE, SIZE), Image.LANCZOS)


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        raise SystemExit(__doc__)
    buffer = io.BytesIO()
    mascot(Path(argv[0])).save(buffer, "PNG", optimize=True)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    lines = [encoded[index:index + 116] for index in range(0, len(encoded), 116)]
    OUT.write_text(
        '"""The Octryx mascot as a base64 PNG (generated by scripts/render_pet_icons.py; do not edit)."""\n\n'
        f"SIZE = {SIZE}\n"
        "MASCOT_PNG = (\n" + "".join(f'    "{line}"\n' for line in lines) + ")\n",
        encoding="utf-8",
    )
    print(f"{OUT} ({len(buffer.getvalue())} bytes PNG)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
