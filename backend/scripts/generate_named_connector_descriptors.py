"""Generate the frontend's named-connection descriptor fixture from the backend descriptors.

The UI tests (``frontend/chat/tests/unit/namedConnections*.test.mjs``) render connector cards from the
descriptors the panel API sends (``GET /admin/chat/api/panel/named-connection-descriptors``, i.e.
``named_connection_view.list_descriptors()``). This script writes exactly that payload into
``frontend/chat/tests/unit/namedConnectorDescriptors.mjs`` so the fixture cannot drift from the server.

Usage (from the repository root or ``backend/``):

    backend/.venv/bin/python backend/scripts/generate_named_connector_descriptors.py          # write
    backend/.venv/bin/python backend/scripts/generate_named_connector_descriptors.py --check  # exit 1 on drift

``tests/services/admin/test_named_connections_descriptor_fixture.py`` runs the check in the backend suite.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
FIXTURE = BACKEND.parent / "frontend" / "chat" / "tests" / "unit" / "namedConnectorDescriptors.mjs"

HEADER = """\
// GENERATED by backend/scripts/generate_named_connector_descriptors.py from the server's connector
// descriptors (backend named_connections/descriptors, `public()`), as the panel API sends them.
// Do not edit by hand: change the descriptor and rerun the script (the backend suite checks for drift).
// Shared by the named-connection UI tests.

import { parseDescriptor } from "../../src/admin/components/namedConnections/namedConnectionsParse.ts";

"""
FOOTER = """
export const D = Object.fromEntries(Object.entries(DESCRIPTORS).map(([name, raw]) => [name, parseDescriptor(raw)]));
"""


def render() -> str:
    """The fixture's full text for the current descriptors."""
    if str(BACKEND) not in sys.path:
        sys.path.insert(0, str(BACKEND))
    from app.services.admin.project.named_connection_view import list_descriptors

    by_name = {item["connector_name"]: item for item in list_descriptors()["connectors"]}
    body = json.dumps(by_name, indent=2, ensure_ascii=False)
    return f"{HEADER}export const DESCRIPTORS = {body};\n{FOOTER}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the fixture differs; write nothing")
    args = parser.parse_args(argv)
    expected = render()
    current = FIXTURE.read_text(encoding="utf-8") if FIXTURE.exists() else ""
    if args.check:
        if current.replace("\r\n", "\n") != expected:
            sys.stderr.write(f"{FIXTURE} is out of date; run {Path(__file__).name} to regenerate it.\n")
            return 1
        return 0
    FIXTURE.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
