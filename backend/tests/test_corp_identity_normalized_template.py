"""S3d — the normalised template as a profile artefact.

The whole path is asset free: python-pptx's own default template is written to a
file and treated exactly like an upload, which is enough to exercise every case
(it has the ``diagram_full`` gap, so a derivative really is generated). The
corporate case uses the synthetic corporate template generated by
``tests.office_template_fixture``.
"""

from __future__ import annotations

import json

from app.services.corp_identity.normalized_template import build_profile_normalization
from app.services.corp_identity.normalized_template_manifest import (
    NORMALIZATION_MANIFEST_NAME,
    NORMALIZED_TEMPLATE_NAME,
    STATUS_NORMALIZED,
    TEMPLATE_SNAPSHOT_NAME,
)
from app.services.corp_identity.normalized_template_resolve import resolve_profile_template_path
from tests.corp_identity_normalized_template_support import (  # noqa: F401
    DERIVED_KEY,
    _variant_template,
    profile_root,
    source,
)

# ---------------------------------------------------------------------------
# case 1 — a new template
# ---------------------------------------------------------------------------


def test_new_template_writes_derivative_manifest_and_snapshot(profile_root, source):  # noqa: F811
    result = build_profile_normalization(source, profile_root)

    assert result["status"] == STATUS_NORMALIZED
    assert (profile_root / NORMALIZED_TEMPLATE_NAME).is_file()
    assert (profile_root / NORMALIZATION_MANIFEST_NAME).is_file()
    assert (profile_root / TEMPLATE_SNAPSHOT_NAME).is_file()

    snapshot = json.loads((profile_root / TEMPLATE_SNAPSHOT_NAME).read_text(encoding="utf-8"))
    derived = [layout for layout in snapshot["layouts"] if layout.get("origin") == "derived"]
    assert [layout["key"] for layout in derived] == [DERIVED_KEY]
    assert result["derived_layout_keys"] == [DERIVED_KEY]


def test_manifest_keeps_paths_relative_and_carries_no_binary(profile_root, source):  # noqa: F811
    build_profile_normalization(source, profile_root)
    raw = (profile_root / NORMALIZATION_MANIFEST_NAME).read_text(encoding="utf-8")
    manifest = json.loads(raw)

    assert manifest["normalized_path"] == NORMALIZED_TEMPLATE_NAME
    assert manifest["snapshot_path"] == TEMPLATE_SNAPSHOT_NAME
    assert str(profile_root) not in raw
    assert manifest["error"] is None
    assert len(manifest["generated_layouts"]) == 1
    # A JSON document that round-trips through str() holds no bytes anywhere.
    assert json.loads(json.dumps(manifest)) == manifest


def test_resolution_prefers_the_current_derivative(profile_root, source):  # noqa: F811
    build_profile_normalization(source, profile_root)
    resolved = resolve_profile_template_path(profile_root, source)

    assert resolved.path == profile_root / NORMALIZED_TEMPLATE_NAME
    assert resolved.origin == "normalized"
    assert resolved.customized is False


# ---------------------------------------------------------------------------
# case 2 — the same file again
# ---------------------------------------------------------------------------


def test_identical_source_is_idempotent_and_rewrites_nothing(profile_root, source):  # noqa: F811
    first = build_profile_normalization(source, profile_root)
    stamps = {
        name: (profile_root / name).stat().st_mtime_ns
        for name in (NORMALIZED_TEMPLATE_NAME, NORMALIZATION_MANIFEST_NAME, TEMPLATE_SNAPSHOT_NAME)
    }
    payload = (profile_root / NORMALIZED_TEMPLATE_NAME).read_bytes()

    second = build_profile_normalization(source, profile_root)

    assert second.get("reused") is True
    assert second["source_sha256"] == first["source_sha256"]
    assert second["normalized_sha256"] == first["normalized_sha256"]
    assert (profile_root / NORMALIZED_TEMPLATE_NAME).read_bytes() == payload
    for name, stamp in stamps.items():
        assert (profile_root / name).stat().st_mtime_ns == stamp


def test_forced_rebuild_reproduces_the_same_derivative(profile_root, source):  # noqa: F811
    first = build_profile_normalization(source, profile_root)
    payload = (profile_root / NORMALIZED_TEMPLATE_NAME).read_bytes()

    second = build_profile_normalization(source, profile_root, force=True)

    assert second.get("reused") is not True
    assert second["normalized_sha256"] == first["normalized_sha256"]
    assert (profile_root / NORMALIZED_TEMPLATE_NAME).read_bytes() == payload


# ---------------------------------------------------------------------------
# case 3 — the original changed
# ---------------------------------------------------------------------------


def test_changed_original_triggers_renormalization(profile_root, tmp_path, source):  # noqa: F811
    first = build_profile_normalization(source, profile_root)

    _variant_template(source)
    second = build_profile_normalization(source, profile_root)

    assert second.get("reused") is not True
    assert second["status"] == STATUS_NORMALIZED
    assert second["source_sha256"] != first["source_sha256"]
    assert second["derived_layout_keys"] == [DERIVED_KEY]


def test_changed_original_without_renormalization_resolves_to_the_original(profile_root, source):  # noqa: F811
    build_profile_normalization(source, profile_root)
    _variant_template(source)

    resolved = resolve_profile_template_path(profile_root, source)

    assert resolved.path == source
    assert resolved.origin == "original"
    assert resolved.status == "stale"
