from __future__ import annotations

import ast
import json
import re
from collections.abc import Iterable, Iterator, Mapping
from pathlib import Path

from tests.guards._support import BACKEND

# Delete work packages removed guard and security tests whose subject was still live; a listed test can only leave
# by moving to RETIRED with the reason it may go.
PROTECTED_DIRS = ("tests/data_access/", "tests/guards/", "tests/content_security/")
PROTECTED_FILES = (
    "tests/middleware/test_workspace_id_routes.py",
    "tests/services/agent_gateway/test_read_only_git_boundary.py",
    "tests/services/auth/test_auth_health_metrics.py",
    "tests/services/connectors/test_database_tool_permissions.py",
    "tests/services/control_plane/test_env_model_access.py",
    "tests/test_configurable_policy_lists.py",
    "tests/test_s4_fragment_four_eyes.py",
)
INVENTORY_FILE = Path(__file__).with_name("_protected_tests_inventory.py")
REGENERATE = ".venv/bin/python -m tests.guards._protected_tests (from backend/)"
_SUBJECT_DELETED = re.compile(r"^subject deleted: \S.*$")
_COVERED_BY = re.compile(r"^covered by (tests/\S+\.py)::(\S+)$")


def scanned_files(root: Path) -> Iterator[Path]:
    for directory in PROTECTED_DIRS:
        yield from sorted((root / directory).rglob("test_*.py"))
    for relative in PROTECTED_FILES:
        if (root / relative).is_file():
            yield root / relative


def file_test_ids(root: Path, path: Path) -> set[str]:
    relative = path.relative_to(root).as_posix()
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and node.name.startswith("test"):
            names.add(node.name)
        elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            names.update(f"{node.name}::{item.name}" for item in node.body
                         if isinstance(item, ast.FunctionDef | ast.AsyncFunctionDef) and item.name.startswith("test"))
    return {f"{relative}::{name}" for name in names}


def present_test_ids(root: Path, files: Iterable[Path]) -> set[str]:
    return {test_id for path in files for test_id in file_test_ids(root, path)}


def _reason_problem(root: Path, test_id: str, reason: str) -> str | None:
    if _SUBJECT_DELETED.match(reason):
        return None
    covered = _COVERED_BY.match(reason)
    if not covered:
        return f"{test_id}: retired reason must read 'subject deleted: <what>' or 'covered by <test id>'"
    path = root / covered.group(1)
    if not path.is_file() or f"{covered.group(1)}::{covered.group(2)}" not in file_test_ids(root, path):
        return f"{test_id}: the covering test {covered.group(1)}::{covered.group(2)} does not exist"
    return None


def inventory_problems(
    root: Path, present: set[str], protected: Iterable[str], retired: Mapping[str, str],
) -> list[str]:
    problems = [f"{test_id}: a protected test disappeared; restore it or move it to RETIRED with its reason"
                for test_id in sorted(set(protected) - present - set(retired))]
    problems += [f"{test_id}: both protected and retired" for test_id in sorted(set(protected) & set(retired))]
    problems += [f"{test_id}: retired but present; drop it from RETIRED"
                 for test_id in sorted(set(retired) & present)]
    problems += [problem for test_id, reason in sorted(retired.items())
                 if (problem := _reason_problem(root, test_id, reason))]
    return problems


def unlisted(present: set[str], protected: Iterable[str]) -> list[str]:
    return sorted(present - set(protected))


# Regenerating only adds: a listed test stays listed whether or not it still exists.
def regenerated(present: set[str], protected: Iterable[str], retired: Mapping[str, str]) -> list[str]:
    return sorted(set(protected) | (present - set(retired)))


def inventory_source(protected: Iterable[str], retired: Mapping[str, str]) -> str:
    rows = "".join(f'    "{test_id}",\n' for test_id in sorted(protected))
    retired_rows = "".join(f'    "{test_id}":\n        {json.dumps(reason)},\n' for test_id, reason in sorted(retired.items()))
    return (
        "from __future__ import annotations\n\n"
        f"# PROTECTED is generated by `{REGENERATE}`, which only adds.\n"
        "# A protected test leaves only by moving to RETIRED, in the same commit, with\n"
        "# 'subject deleted: <what>' or 'covered by <test id>'.\n"
        f"PROTECTED: tuple[str, ...] = (\n{rows})\n\n"
        f"RETIRED: dict[str, str] = {{\n{retired_rows}}}\n"
    )


if __name__ == "__main__":
    from tests.guards._protected_tests_inventory import PROTECTED, RETIRED

    found = present_test_ids(BACKEND, scanned_files(BACKEND))
    INVENTORY_FILE.write_text(inventory_source(regenerated(found, PROTECTED, RETIRED), RETIRED), encoding="utf-8")
