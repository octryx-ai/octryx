"""Layout catalogue and sample slides of the synthetic test template.

What the template generated by ``tests.office_template_fixture`` contains: the
layouts of each master (names, placeholder types, idx and geometry, backdrops,
icon holders) and the sample slides that teach layout usage. Every value here is
made up; nothing is taken from a real corporate template.
"""

from __future__ import annotations

from dataclasses import dataclass

SLIDE_W, SLIDE_H = 9_144_000, 5_143_500
#: The gutter every regular layout starts its content at (5 mm).
GUTTER = 180_000
CHROME_TOP = 4_800_000

THEME_NAME = "Synthetic Brand 2026"
BRAND_FONT = "Verdana"
BRAND_ACCENT1 = "#1F6F5C"

_TITLE = (GUTTER, GUTTER, SLIDE_W - 2 * GUTTER, 720_000)
_BODY = (GUTTER, 1_080_000, SLIDE_W - 2 * GUTTER, 3_540_000)
_FULL = (0, 0, SLIDE_W, SLIDE_H)


@dataclass(frozen=True)
class Ph:
    """One layout placeholder: OOXML type, idx, rectangle and optional styling."""

    kind: str
    idx: int
    rect: tuple[int, int, int, int]
    color: str = ""  # ``scheme:<slot>`` or ``#RRGGBB``
    size: int = 0  # hundredths of a point
    fill: bool = False


@dataclass(frozen=True)
class Layout:
    name: str
    placeholders: tuple[Ph, ...]
    #: ``bg`` paints ``p:bg``; ``picture`` places a full-slide decorative picture.
    backdrop: str = ""
    icon_holders: tuple[tuple[int, int, int, int], ...] = ()
    #: ``sldLayout@type`` as presentation editors write it; empty = custom layout.
    kind: str = ""


def _chrome() -> tuple[Ph, ...]:
    return (
        Ph("ftr", 30, (GUTTER, CHROME_TOP, 3_000_000, 230_000)),
        Ph("sldNum", 31, (3_360_000, CHROME_TOP, 1_200_000, 230_000)),
    )


def _title(**style: object) -> Ph:
    return Ph("title", 0, _TITLE, **style)  # type: ignore[arg-type]


def _icon_layout() -> Layout:
    width, step = 2_664_000, 2_880_000
    columns = [GUTTER + 180_000 + index * step for index in range(3)]
    placeholders: list[Ph] = [_title()]
    holders = []
    for index, x in enumerate(columns):
        placeholders.append(Ph("body", 16 + 2 * index, (x, 2_232_000, width, 400_000)))
        placeholders.append(Ph("body", 17 + 2 * index, (x, 2_700_000, width, 1_500_000)))
        holders.append((x + (width - 864_000) // 2, 1_224_000, 864_000, 864_000))
    return Layout("Icons 3 Topics", (*placeholders, *_chrome()), icon_holders=tuple(holders))


def _picture_full(name: str, *, titlebar: bool) -> Layout:
    title = Ph("title", 0, (GUTTER, 4_320_000, SLIDE_W - 2 * GUTTER, 576_000), color="#FFFFFF", fill=titlebar)
    return Layout(name, (Ph("pic", 13, _FULL), title))


