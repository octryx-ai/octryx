def master_placeholders() -> list[Ph]:
    """The slide master's own placeholders: title, body and the chrome row."""
    return [_title(), Ph("body", 1, _BODY), *_chrome()]


def second_master_layouts() -> list[Layout]:
    """A second master repeating four names, as multi-master templates do."""
    keep = {"Title Slide", "Title and Content", "Title Only", "Section Header"}
    return [layout for layout in brand_layouts() if layout.name in keep]


