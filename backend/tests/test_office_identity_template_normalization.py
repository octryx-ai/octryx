def test_the_derivative_is_a_loadable_presentation(normalized_default):  # noqa: F811
    presentation = _load(Path(normalized_default["output_path"]))
    names = [layout.name for master in presentation.slide_masters for layout in master.slide_layouts]
    assert DIAGRAM_FULL_NAME in names


def test_the_generated_layout_is_in_the_catalog(normalized_default):  # noqa: F811
    snapshot = build_template_snapshot(normalized_default["output_path"])
    assert snapshot["summary"]["layout_count"] == normalized_default["layout_count_after"]
    layout = layout_by_key(snapshot, DERIVED_KEY)
    assert layout is not None
    assert layout["name"] == DIAGRAM_FULL_NAME
    assert layout["content_shape"] == "diagram_full"


def test_the_catalog_states_the_origin(normalized_default):  # noqa: F811
    snapshot = build_template_snapshot(normalized_default["output_path"])
    derived = layout_by_key(snapshot, DERIVED_KEY)
    assert derived["origin"] == "derived"
    assert derived["derived_shape"] == "diagram_full"
    assert derived["derived_from"] == normalized_default["generated_layouts"][0]["cloned_from"]
    others = [
        layout for layout in snapshot["layouts"] if layout["key"] != DERIVED_KEY
    ]
    assert others and all(layout["origin"] == "template" for layout in others)
