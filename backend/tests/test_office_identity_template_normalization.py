# ---------------------------------------------------------------------------


def test_the_gap_is_real_in_the_default_template(default_template):  # noqa: F811
    """No stock layout offers a large picture area that spares the title."""
    snapshot = build_template_snapshot(default_template)
    assert find_diagram_full_layout(snapshot) is None


def test_a_derivative_is_produced_for_the_gap(normalized_default):  # noqa: F811
    assert normalized_default["status"] == "normalized"
    assert normalized_default["covered_by_template"] == {"diagram_full": None}
    assert len(normalized_default["generated_layouts"]) == 1
    assert Path(normalized_default["output_path"]).is_file()


def test_a_covered_template_produces_nothing(tmp_path, normalized_default):  # noqa: F811
    """The derivative covers the shape, so normalising it again is a no-op —
    no second derivative, and explicitly no empty alibi file."""
    output = tmp_path / "second.pptx"
    report = normalize_template(normalized_default["output_path"], output)
    assert report["status"] == "unchanged"
    assert report["generated_layouts"] == []
    assert report["output_path"] is None
    assert report["manifest_path"] is None
    assert report["covered_by_template"]["diagram_full"] == DERIVED_KEY
    assert not output.exists()
    assert not (tmp_path / MANIFEST_NAME).exists()


def test_gap_analysis_needs_a_large_area_not_just_a_picture(default_template):  # noqa: F811
    """The threshold, not the mere presence of a picture slot, is the test:
    the stock picture layout holds 36 % of the slide and does not qualify."""
    snapshot = build_template_snapshot(default_template)
    caption = layout_by_key(snapshot, "picture-with-caption")
    assert caption is not None
    ratio = _picture_slot(caption)["slide_area_ratio"]
    assert 0 < ratio < DIAGRAM_MIN_AREA_RATIO


