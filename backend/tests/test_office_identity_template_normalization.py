"""S3c — template normalisation: gap analysis, layout authoring, identity.

Most cases run against python-pptx's own default template, which is written to
a file and then treated like any other upload; the corporate cases run against
the synthetic corporate templates generated by ``tests.office_template_fixture``.
"""

from __future__ import annotations

import io
from pathlib import Path

from app.services.office_identity.diagram_layout_gaps import (
    DIAGRAM_FULL_NAME,
    DIAGRAM_MIN_AREA_RATIO,
    content_band,
    find_diagram_full_layout,
    template_chrome_top_emu,
)
from app.services.office_identity.package import potx_bytes_to_pptx_bytes
from app.services.office_identity.template_normalization import MANIFEST_NAME, normalize_template
from app.services.office_identity.template_snapshot import (
    build_template_snapshot,
    layout_by_key,
    slots_by_role,
)
from tests.office_identity_template_normalization_support import (  # noqa: F401
    DERIVED_KEY,
    _picture_slot,
    default_template,
    normalized_default,
)


def _load(path: Path):
    from pptx import Presentation

    return Presentation(io.BytesIO(potx_bytes_to_pptx_bytes(Path(path).read_bytes())))


