def test_the_band_clears_title_and_chrome(default_template):  # noqa: F811
    snapshot = build_template_snapshot(default_template)
    layout = layout_by_key(snapshot, "picture-with-caption")
    chrome_top = template_chrome_top_emu(snapshot.get("layouts", []))
    band = content_band(snapshot, layout, 457200, chrome_top)
    assert band is not None
    title = slots_by_role(layout, "title")[0]
    height = snapshot["slide_size"]["height_emu"]
    # This template's caption title sits in the lower half, so the band has to
    # end above it rather than start below it.
    assert title["y_emu"] + title["h_emu"] / 2 > height / 2
    assert band["y_emu"] + band["h_emu"] <= title["y_emu"]


def test_the_derived_picture_is_large_and_covers_nothing(normalized_default):  # noqa: F811
    snapshot = build_template_snapshot(normalized_default["output_path"])
    layout = layout_by_key(snapshot, DERIVED_KEY)
    slot = _picture_slot(layout)
    assert slot["slide_area_ratio"] >= DIAGRAM_MIN_AREA_RATIO
    assert slot["full_bleed"] is False
    assert slot["covers"] == []
    assert slots_by_role(layout, "title"), "the derived layout must keep its title"


def test_the_band_is_never_invented(default_template):  # noqa: F811
    """A layout whose title leaves no room yields ``None`` instead of a guess."""
    snapshot = build_template_snapshot(default_template)
    layout = dict(layout_by_key(snapshot, "picture-with-caption"))
    layout["slots"] = [
        {**slot, "y_emu": 0, "h_emu": snapshot["slide_size"]["height_emu"]}
        if slot["role"] == "title"
        else slot
        for slot in layout["slots"]
    ]
    assert content_band(snapshot, layout, 457200, None) is None


