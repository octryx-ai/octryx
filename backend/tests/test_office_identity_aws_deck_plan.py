def test_full_slide_picture_shape_counts_as_a_layout_backdrop(brand_normalized):
    """The branded title slide counts its full-slide picture as the layout backdrop.

    Its white title is legible because the layout places the brand gradient as
    a full-slide ``p:pic`` — not as ``p:bg``. Reading only ``p:bg`` would make the
    gate report ``title_illegible`` for a slide the render shows in white on
    the blue gradient.
    """
    _, snapshot = brand_normalized
    title_layout = next(layout for layout in snapshot["layouts"] if layout["key"] == "title-slide")
    assert title_layout["has_background"] is True
    title_slot = next(slot for slot in title_layout["slots"] if slot["role"] == "title")
    assert title_slot["font_color"] == "scheme:bg1"  # white — only safe on a backdrop


def test_plan_composes_into_a_branded_deck_without_warnings(brand_normalized, tmp_path):
    diagram_png = tmp_path / DIAGRAM_PNG.name
    diagram_png.write_bytes(png_bytes(1600, 900, (255, 255, 255)))
    template_path, snapshot = brand_normalized
    plan = build_aws_deck_plan(
        _aws_snapshot(),
        snapshot,
        knowledge_facts=_knowledge_facts(),
        diagram_images=_diagram_images(diagram_png),
    )
    output = tmp_path / "aws-deck.pptx"
    result = build_presentation_from_plan(template_path, snapshot, plan, output)
    assert result["slide_count"] == len(plan)
    assert output.is_file()

    findings = check_deck_quality(snapshot, plan, output)
    warnings = [finding for finding in findings if finding.get("severity") == "warning"]
    assert warnings == [], warnings
    # the diagram really landed in a picture slot
    assert any(label.startswith("picture@") for label in result["filled_slots"])


