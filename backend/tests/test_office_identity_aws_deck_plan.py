@pytest.fixture(scope="module")
def brand_normalized(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, dict[str, Any]]:
    """The *normalised* corporate template (S3c derivative) and its snapshot."""
    source = write_template(tmp_path_factory.mktemp("corporate") / "brand.potx", "brand")
    output = tmp_path_factory.mktemp("normalized") / "normalized.potx"
    result = normalize_template(source, output)
    template = Path(result.get("output_path") or output)
    if not template.is_file():  # `unchanged` means the original already covers it
        template = source
    return template, build_template_snapshot(template)


