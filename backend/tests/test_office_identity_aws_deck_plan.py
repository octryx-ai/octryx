def test_themed_knowledge_fact_moves_onto_its_theme_slide():
    plan = _plan(_corporate_template(), diagram_images=_diagram_images(), knowledge_facts=_knowledge_facts())
    runtime = next(entry for entry in plan if entry["title"].startswith("Compute"))
    data = next(entry for entry in plan if entry["title"].startswith("Data and storage"))
    # the EKS fact lands on the compute theme, the RDS fact on the data theme,
    # each keeping ``| Source: knowledge:<id>`` in the notes
    assert "EKS" in " ".join(runtime["bullets"])
    assert "knowledge:knowledge_graph:node/platform-runtime" in runtime["notes"]
    assert "RDS" in " ".join(data["bullets"])
    assert "knowledge:knowledge_graph:node/data-tier" in data["notes"]
    # both facts were consumed, so no separate context slide is produced
    assert not [entry for entry in plan if entry["title"] == "Domain context"]


def test_ambiguous_fact_stays_on_the_context_slide():
    # "subnets" (network) and "firewall" (security) both match, so the fact
    # is not uniquely themed and keeps its place on the context slide rather
    # than being forced onto a theme it only half belongs to.
    assert classify_fact_topic("The subnets sit behind a firewall") == ""
    facts = [
        {"statement": "The subnets sit behind a firewall", "source": "knowledge:node/segmentation"}
    ]
    plan = _plan(_corporate_template(), diagram_images=_diagram_images(), knowledge_facts=facts)
    context = next(entry for entry in plan if entry["title"] == "Domain context")
    assert any("firewall" in bullet for bullet in context["bullets"])
    # it did not leak onto a theme slide
    for entry in plan:
        if entry["title"].startswith(("Network", "Identity")):
            assert "firewall" not in " ".join(entry.get("bullets") or [])


def test_small_deck_gets_no_section_dividers():
    plan = build_aws_deck_plan(_tiny_snapshot_for_dosing(), _corporate_template())
    # A short deck reads as a plain sequence; dosing suppresses every divider.
    assert not [entry for entry in plan if entry.get("content_shape") == "section"]


def test_large_deck_earns_a_divider_only_before_a_multi_slide_block():
    plan = _plan(_corporate_template(), diagram_images=_diagram_images(), knowledge_facts=_knowledge_facts())
    section_titles = [entry["title"] for entry in plan if entry.get("content_shape") == "section"]
    # The multi-slide resource block earns its divider; the single-slide diagram
    # block does not, so "Architecture at a glance" gets no header.
    assert "Resources in detail" in section_titles
    assert "Architecture at a glance" not in section_titles


def test_structural_slides_are_dropped_when_the_template_cannot_carry_them():
    """A template without the shapes yields a deck without them — not a crash."""
    bare = {
        "slide_size": {"width_emu": 9144000, "height_emu": 5143500},
        "layouts": [
            {
                "key": "title-and-content",
                "content_shape": "bullets",
                "capacity": {
                    "content_units": 1,
                    "picture_slots": 0,
                    "title_slots": 1,
                    "subtitle_slots": 0,
                },
            }
        ],
    }
    plan = _plan(bare)
    # ``None`` is the title slide: this template offers no ``title_slide``
    # shape either, so the composer decides that one on capacity alone.
    shapes = {entry.get("content_shape") for entry in plan}
    assert shapes == {"bullets", None}, shapes
    assert not shapes & {"statement", "icons_3", "section", "agenda"}
    # no section header slide survived, and no slide lost its evidence
    assert not [entry for entry in plan if entry["title"] in SECTION_TITLES]
    assert plan[-1]["title"].startswith(OPEN_POINTS_TITLE)
