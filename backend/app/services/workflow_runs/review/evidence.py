"""What the reviewer sees: built by the server from the run's own record and working copy.

The reviewer starts from a fresh context. It gets no message, tool trace or answer of the author's session —
only facts the server reads itself: the Work item, the tests a person confirmed, the newest test run, and the
change:

- a server run: the working copy's whole change against the run's base commit (``context.base_sha``, else
  ``HEAD``), new files included, read with ``safe_git`` (nothing the working copy configures runs, ``-diff``
  hides nothing);
- a device run (octryx-claude): the launcher's patch of **this** pass (``octryx/facts``; cleared when a phase is
  entered) is applied to the server's working copy of the run's branch, and the reviewer reviews that copy — the
  very tree the platform later pushes (``platform/scm.push`` compares the hashes). Without a server working copy
  the patch itself is reviewed and nothing can be pushed;
- no change (an empty one, the device lacking the base commit, a patch that does not apply) or a change larger
  than a review takes (:data:`MAX_DIFF`): no review — the run pauses ``review_no_decision`` with the reason
  (``runner``), never a verdict on nothing or on part of a diff.

Each section is fenced with markers that are new for every review, and the reviewer's system message says the
content is untrusted data, never instructions (a ticket or a code comment cannot steer the verdict).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from sqlalchemy import select
