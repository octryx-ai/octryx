/** The primary-section props picked from the main-area props; a missing prop is passed as undefined. */
export function pickWorkspacePrimarySectionProps(
  props: Record<string, unknown>,
): Record<string, unknown> {
  const picked: Record<string, unknown> = {};
  for (const key of WORKSPACE_PRIMARY_SECTION_PROP_KEYS) {
    picked[key] = props[key];
  }
  return picked;
}
